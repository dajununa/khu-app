// 강의실마다 요일별로 수업을 2~4개씩 (같은 결과가 나오도록 호실 번호로 고정)
const SCHEDULES = [];
for (const r of ROOMS) {
  let seed = [...r.code].reduce((a, c) => a * 31 + c.charCodeAt(0), 7);
  const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);
  for (let wd = 1; wd <= 5; wd++) {
    const n = 2 + Math.floor(rnd() * 3);
    const picked = new Set();
    while (picked.size < n) picked.add(Math.floor(rnd() * SLOTS.length));
    [...picked].sort().forEach(i => SCHEDULES.push({ id: `ex-${r.code}-${wd}-${i}`, room_id: r.id, weekday: wd, start_time: SLOTS[i][0], end_time: SLOTS[i][1], title: COURSES[Math.floor(rnd() * COURSES.length)] }));
  }
}

